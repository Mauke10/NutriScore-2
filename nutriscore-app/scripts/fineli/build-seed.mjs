// Builds supabase/seed_009_fineli_foods.sql from the Fineli open-data
// package (Finnish food composition database, THL, CC BY 4.0) plus the
// Estonian names in ./et-names.json.
//
//   node scripts/fineli/build-seed.mjs <path-to-unzipped-Fineli-package>
//
// The package directory is the "basic package" zip from
// https://fineli.fi/fineli/en/avoin-data (food.csv, component_value.csv,
// foodname_EN.csv, foodname_FI.csv; semicolon-separated, latin1, decimal
// commas). It isn't committed here — only the generated SQL is.
//
// The output upserts on (source, source_id), so re-running it after a new
// Fineli release or after adding Estonian names updates rows in place
// without touching use_count (how often you've picked each food).
//
// It also cross-checks every food's stated energy against its macros
// (Fineli's own conversion factors) and prints anything that disagrees by
// more than 10%, so a corrupted copy of the data would be caught here
// rather than silently showing up as wrong calories in the app.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildSearchText } from "../../lib/foodText.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = process.argv[2];
if (!srcDir) {
  console.error("usage: node scripts/fineli/build-seed.mjs <fineli-package-dir>");
  process.exit(1);
}
const outFile = path.join(here, "../../supabase/seed_009_fineli_foods.sql");
const CHUNK = 400;

function readCsv(name) {
  const text = fs.readFileSync(path.join(srcDir, name), "latin1");
  return text
    .split(/\r?\n/)
    .slice(1)
    .filter(Boolean)
    .map((line) => line.split(";"));
}

const foods = readCsv("food.csv"); // FOODID;FOODNAME;FOODTYPE;...
const namesEn = Object.fromEntries(readCsv("foodname_EN.csv").map((r) => [r[0], r[1]]));
const namesFi = Object.fromEntries(readCsv("foodname_FI.csv").map((r) => [r[0], r[1]]));

const WANTED = new Set(["ENERC", "PROT", "CHOAVL", "FAT", "FIBC", "ALC", "OA", "SUGOH"]);
const values = {};
for (const [id, comp, val] of readCsv("component_value.csv")) {
  if (!WANTED.has(comp)) continue;
  (values[id] ||= {})[comp] = Number(val.replace(",", "."));
}

const etNames = JSON.parse(fs.readFileSync(path.join(here, "et-names.json"), "utf8"));
delete etNames._comment;
for (const id of Object.keys(etNames)) {
  if (!namesEn[id]) throw new Error("et-names.json refers to Fineli id " + id + ", which isn't in this Fineli package");
}

const round1 = (n) => Math.round(n * 10) / 10;
const sqlStr = (s) => (s == null ? "null" : "'" + String(s).replace(/'/g, "''") + "'");
const sqlNum = (n) => (n == null || Number.isNaN(n) ? "null" : String(n));
const sqlArr = (a) => (a.length ? "array[" + a.map(sqlStr).join(",") + "]::text[]" : "'{}'::text[]");

const rows = [];
const energyMismatches = [];
for (const [id, , foodType] of foods) {
  const v = values[id];
  if (!v || v.ENERC == null) continue; // a handful of Fineli rows carry no energy value at all
  const et = etNames[id];
  const nameEn = namesEn[id] || null;
  const nameFi = namesFi[id] || null;
  const food = {
    source_id: id,
    name: et ? et.et : nameEn || nameFi,
    name_en: nameEn,
    name_fi: nameFi,
    aliases: et ? et.aliases || [] : [],
    kind: foodType === "DISH" ? "dish" : "food",
    calories: round1(v.ENERC / 4.184),
    protein: round1(v.PROT ?? 0),
    carbs: round1(v.CHOAVL ?? 0),
    fat: round1(v.FAT ?? 0),
    fiber: round1(v.FIBC ?? 0)
  };
  food.search_text = buildSearchText(food);
  rows.push(food);

  // Fineli's energy factors, kJ/g: protein 17, fat 37, available carbs 17,
  // fibre 8, alcohol 29, organic acids 13, sugar alcohols 10.
  const expectedKj =
    17 * (v.PROT ?? 0) + 37 * (v.FAT ?? 0) + 17 * (v.CHOAVL ?? 0) + 8 * (v.FIBC ?? 0) + 29 * (v.ALC ?? 0) + 13 * (v.OA ?? 0) + 10 * (v.SUGOH ?? 0);
  if (v.ENERC > 40 && Math.abs(expectedKj - v.ENERC) / v.ENERC > 0.1) {
    energyMismatches.push(`${id} ${food.name}: stated ${Math.round(v.ENERC)} kJ, macros give ${Math.round(expectedKj)} kJ`);
  }
}

let sql =
  "-- Generated by scripts/fineli/build-seed.mjs — do not edit by hand.\n" +
  "-- Source: Fineli, Finnish food composition database, THL (https://fineli.fi), CC BY 4.0.\n" +
  "-- Estonian names/aliases: scripts/fineli/et-names.json.\n" +
  "-- " + rows.length + " foods. Safe to re-run: upserts on (source, source_id) and leaves use_count alone.\n" +
  "-- Run after migration_009_foods.sql.\n";

for (let i = 0; i < rows.length; i += CHUNK) {
  const chunk = rows.slice(i, i + CHUNK);
  sql +=
    "\ninsert into foods (source, source_id, name, name_en, name_fi, aliases, search_text, kind, calories_per_100g, protein_per_100g, carbs_per_100g, fat_per_100g, fiber_per_100g) values\n" +
    chunk
      .map(
        (f) =>
          `('fineli',${sqlStr(f.source_id)},${sqlStr(f.name)},${sqlStr(f.name_en)},${sqlStr(f.name_fi)},${sqlArr(f.aliases)},${sqlStr(f.search_text)},${sqlStr(f.kind)},${sqlNum(f.calories)},${sqlNum(f.protein)},${sqlNum(f.carbs)},${sqlNum(f.fat)},${sqlNum(f.fiber)})`
      )
      .join(",\n") +
    "\non conflict (source, source_id) do update set name = excluded.name, name_en = excluded.name_en, name_fi = excluded.name_fi, aliases = excluded.aliases, search_text = excluded.search_text, kind = excluded.kind, calories_per_100g = excluded.calories_per_100g, protein_per_100g = excluded.protein_per_100g, carbs_per_100g = excluded.carbs_per_100g, fat_per_100g = excluded.fat_per_100g, fiber_per_100g = excluded.fiber_per_100g;\n";
}

fs.writeFileSync(outFile, sql);
console.log(`Wrote ${rows.length} foods (${Object.keys(etNames).length} with Estonian names) to ${path.relative(process.cwd(), outFile)}`);
console.log(`Energy cross-check: ${energyMismatches.length} foods where stated energy and macros disagree by >10%`);
for (const line of energyMismatches) console.log("  " + line);
